import 'package:feather_icons/feather_icons.dart';
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:provider/provider.dart';
import '../../../../core/theme/app_colors.dart';
import '../../../../core/theme/app_typography.dart';
import '../../../../core/widgets/app_button.dart';
import '../../../../core/widgets/app_scaffold.dart';
import '../../../../core/widgets/pill_badge.dart';
import '../../../../core/widgets/progress_bar.dart';
import '../../../../core/widgets/section_title.dart';
import '../../../dashboard/presentation/pages/main_nav_page.dart';
import '../controllers/interview_controller.dart';
import 'create_interview_page.dart';
import 'question_review_page.dart';

class InterviewResultPage extends StatelessWidget {
  const InterviewResultPage({super.key});

  void _showShareReportModal(BuildContext context, dynamic eval, dynamic config) {
    final colors = AppColorScheme.of(context);
    final overall = eval?.overallScore ?? 84;
    final role = config.role;
    final company = config.company;
    final hiringBand = eval?.hiringBand ?? 'Strong Hire';
    final percentile = eval?.benchmark.percentile ?? 88;

    final reportMarkdown = '''
========================================
AI MOCK INTERVIEW DEBRIEF REPORT
========================================
Candidate Target Role: $role
Company Profile: $company
Overall Performance Score: $overall / 100
Hiring Recommendation: $hiringBand
Percentile Standing: Top ${100 - (percentile as int)}% of Applicants

EXECUTIVE SUMMARY:
${eval?.summary ?? 'Candidate demonstrated solid technical mastery and structured answers.'}

CATEGORY BREAKDOWN:
${eval?.skillScores.entries.map((e) => '• ${e.key}: ${e.value}/100').join('\n') ?? ''}

STRENGTHS:
${eval?.strengths.map((s) => '✓ $s').join('\n') ?? ''}

HIGH-YIELD IMPROVEMENT AREAS:
${eval?.areasToImprove.map((a) => '→ $a').join('\n') ?? ''}

Generated by AI Interview Coach Platform
========================================
''';

    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: colors.card,
      shape: const RoundedRectangleBorder(
        borderRadius: BorderRadius.vertical(top: Radius.circular(28)),
      ),
      builder: (ctx) {
        return Padding(
          padding: const EdgeInsets.fromLTRB(24, 20, 24, 36),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Row(
                mainAxisAlignment: MainAxisAlignment.spaceBetween,
                children: [
                  Text(
                    'Export Performance Debrief',
                    style: AppTypography.bold(18, color: colors.foreground),
                  ),
                  IconButton(
                    icon: Icon(FeatherIcons.x, size: 18, color: colors.mutedForeground),
                    onPressed: () => Navigator.of(ctx).pop(),
                  ),
                ],
              ),
              const SizedBox(height: 12),
              Container(
                width: double.infinity,
                padding: const EdgeInsets.all(14),
                decoration: BoxDecoration(
                  color: colors.secondary,
                  borderRadius: BorderRadius.circular(16),
                  border: Border.all(color: colors.border),
                ),
                child: Text(
                  reportMarkdown,
                  style: AppTypography.regular(10, color: colors.foreground, height: 1.45),
                  maxLines: 12,
                  overflow: TextOverflow.ellipsis,
                ),
              ),
              const SizedBox(height: 20),
              Row(
                children: [
                  Expanded(
                    child: AppButton(
                      label: 'Copy Report to Clipboard',
                      icon: FeatherIcons.clipboard,
                      onPress: () {
                        Clipboard.setData(ClipboardData(text: reportMarkdown));
                        Navigator.of(ctx).pop();
                        ScaffoldMessenger.of(context).showSnackBar(
                          const SnackBar(content: Text('Interview report copied to clipboard!')),
                        );
                      },
                    ),
                  ),
                ],
              ),
            ],
          ),
        );
      },
    );
  }

  @override
  Widget build(BuildContext context) {
    final colors = AppColorScheme.of(context);
    final interviewCtrl = context.watch<InterviewController>();
    final eval = interviewCtrl.lastEvaluation;
    final config = interviewCtrl.config;

    final overallScore = eval?.overallScore ?? 84;
    final performanceLabel = eval?.performanceLabel ?? 'Strong Candidate Profile';
    final hiringBand = eval?.hiringBand ?? 'Strong Hire';
    final summary = eval?.summary ??
        'You explained your project clearly and showed strong technical fundamentals. Go deeper on architectural trade-offs next time.';
    final benchmark = eval?.benchmark;

    final scores = eval != null
        ? eval.skillScores.entries.map((e) {
            final val = e.value;
            final note = val >= 85
                ? 'Strong'
                : val >= 75
                    ? 'Good'
                    : 'Growing';
            return {'label': e.key, 'value': val, 'note': note};
          }).toList()
        : [
            {'label': 'Technical Knowledge', 'value': 88, 'note': 'Strong'},
            {'label': 'Communication & Clarity', 'value': 82, 'note': 'Good'},
            {'label': 'Problem Solving & Architecture', 'value': 86, 'note': 'Strong'},
            {'label': 'Confidence & Delivery', 'value': 79, 'note': 'Good'},
            {'label': 'Role Mastery', 'value': 90, 'note': 'Strong'},
          ];

    final strengths = eval?.strengths ?? [
      'Strong grasp of core architecture and separation of concerns.',
      'Articulate explanation of real project workflows and repository layers.',
    ];

    final areasToImprove = eval?.areasToImprove ?? [
      'Go deeper on distributed system trade-offs and offline sync edge cases.',
      'Include measurable metrics and business impact in behavioral answers.',
    ];

    final studyPlan = eval?.studyPlan ?? [];

    return AppScaffold(
      body: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          // Top Bar
          Padding(
            padding: const EdgeInsets.symmetric(vertical: 8.0),
            child: Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                IconButton(
                  icon: Icon(FeatherIcons.x, size: 21, color: colors.foreground),
                  onPressed: () {
                    Navigator.of(context).pushAndRemoveUntil(
                      MaterialPageRoute(builder: (_) => const MainNavPage()),
                      (route) => false,
                    );
                  },
                ),
                Text(
                  'Interview Debrief & Report',
                  style: AppTypography.bold(17, color: colors.foreground),
                ),
                IconButton(
                  icon: Icon(FeatherIcons.share2, size: 18, color: colors.foreground),
                  onPressed: () => _showShareReportModal(context, eval, config),
                ),
              ],
            ),
          ),

          // Score Hero Card
          Container(
            width: double.infinity,
            padding: const EdgeInsets.all(22),
            decoration: BoxDecoration(
              color: colors.navy,
              borderRadius: BorderRadius.circular(26),
            ),
            child: Column(
              children: [
                Row(
                  mainAxisAlignment: MainAxisAlignment.spaceBetween,
                  children: [
                    PillBadge(label: hiringBand, tone: PillTone.success),
                    Text(
                      config.company,
                      style: AppTypography.semiBold(11, color: const Color(0xFFBFCBE5)),
                    ),
                  ],
                ),
                const SizedBox(height: 16),
                Container(
                  width: 120,
                  height: 120,
                  decoration: BoxDecoration(
                    shape: BoxShape.circle,
                    border: Border.all(color: colors.mint, width: 5),
                  ),
                  alignment: Alignment.center,
                  child: Column(
                    mainAxisAlignment: MainAxisAlignment.center,
                    children: [
                      Text(
                        '$overallScore',
                        style: AppTypography.bold(40, color: Colors.white),
                      ),
                      Text(
                        '/ 100',
                        style: AppTypography.medium(11, color: const Color(0xFFBFCBE5)),
                      ),
                    ],
                  ),
                ),
                const SizedBox(height: 14),
                Text(
                  performanceLabel,
                  style: AppTypography.bold(16, color: Colors.white),
                ),
                const SizedBox(height: 4),
                Text(
                  '${config.role} · ${config.type}',
                  style: AppTypography.regular(11, color: const Color(0xFFBFCBE5)),
                ),
              ],
            ),
          ),

          // Benchmark Card
          if (benchmark != null) ...[
            const SizedBox(height: 14),
            Container(
              padding: const EdgeInsets.all(16),
              decoration: BoxDecoration(
                color: colors.card,
                borderRadius: BorderRadius.circular(20),
                border: Border.all(color: colors.border),
              ),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Row(
                    mainAxisAlignment: MainAxisAlignment.spaceBetween,
                    children: [
                      Row(
                        children: [
                          Icon(FeatherIcons.trendingUp, size: 16, color: colors.mint),
                          const SizedBox(width: 8),
                          Text('Industry Benchmark', style: AppTypography.bold(13, color: colors.foreground)),
                        ],
                      ),
                      Container(
                        padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 4),
                        decoration: BoxDecoration(
                          color: colors.mint.withValues(alpha: 0.15),
                          borderRadius: BorderRadius.circular(8),
                        ),
                        child: Text(
                          'Top ${100 - benchmark.percentile}%',
                          style: AppTypography.bold(11, color: colors.mint),
                        ),
                      ),
                    ],
                  ),
                  const SizedBox(height: 10),
                  Text(
                    'You scored higher than ${benchmark.percentile}% of candidates preparing for ${config.role} roles.',
                    style: AppTypography.regular(11, color: colors.mutedForeground, height: 1.45),
                  ),
                  const SizedBox(height: 10),
                  Container(
                    padding: const EdgeInsets.all(10),
                    decoration: BoxDecoration(
                      color: colors.secondary,
                      borderRadius: BorderRadius.circular(12),
                    ),
                    child: Row(
                      children: [
                        Icon(FeatherIcons.checkCircle, size: 14, color: colors.primary),
                        const SizedBox(width: 8),
                        Expanded(
                          child: Text(
                            benchmark.readinessLevel,
                            style: AppTypography.semiBold(11, color: colors.foreground),
                          ),
                        ),
                      ],
                    ),
                  ),
                ],
              ),
            ),
          ],

          const SectionTitle(title: 'Executive Evaluation'),
          Container(
            padding: const EdgeInsets.all(16),
            decoration: BoxDecoration(
              color: colors.card,
              borderRadius: BorderRadius.circular(20),
              border: Border.all(color: colors.border),
            ),
            child: Text(
              summary,
              style: AppTypography.regular(12, color: colors.foreground, height: 1.55),
            ),
          ),

          const SectionTitle(title: 'Skill Competency Breakdown'),
          Container(
            padding: const EdgeInsets.all(16),
            decoration: BoxDecoration(
              color: colors.card,
              borderRadius: BorderRadius.circular(20),
              border: Border.all(color: colors.border),
            ),
            child: Column(
              children: scores.map((item) {
                final label = item['label'] as String;
                final value = item['value'] as int;
                final note = item['note'] as String;
                final isGrowing = note == 'Growing';

                return Padding(
                  padding: const EdgeInsets.only(bottom: 14.0),
                  child: Column(
                    children: [
                      Row(
                        mainAxisAlignment: MainAxisAlignment.spaceBetween,
                        children: [
                          Text(label, style: AppTypography.medium(12, color: colors.foreground)),
                          Text(note, style: AppTypography.regular(10, color: colors.mutedForeground)),
                        ],
                      ),
                      const SizedBox(height: 8),
                      Row(
                        children: [
                          Expanded(
                            child: ProgressBar(
                              value: value.toDouble(),
                              color: isGrowing ? colors.coral : colors.primary,
                              height: 7,
                            ),
                          ),
                          const SizedBox(width: 10),
                          SizedBox(
                            width: 34,
                            child: Text(
                              '$value%',
                              style: AppTypography.bold(12, color: colors.foreground),
                              textAlign: TextAlign.right,
                            ),
                          ),
                        ],
                      ),
                    ],
                  ),
                );
              }).toList(),
            ),
          ),

          const SectionTitle(title: 'Key Strengths Observed'),
          Container(
            padding: const EdgeInsets.all(16),
            decoration: BoxDecoration(
              color: colors.card,
              borderRadius: BorderRadius.circular(20),
              border: Border.all(color: colors.border),
            ),
            child: Column(
              children: strengths.map((s) {
                return Padding(
                  padding: const EdgeInsets.only(bottom: 8.0),
                  child: Row(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Icon(FeatherIcons.check, size: 14, color: colors.mint),
                      const SizedBox(width: 8),
                      Expanded(
                        child: Text(s, style: AppTypography.regular(11, color: colors.foreground, height: 1.4)),
                      ),
                    ],
                  ),
                );
              }).toList(),
            ),
          ),

          const SectionTitle(title: 'High-Impact Improvement Areas'),
          Container(
            padding: const EdgeInsets.all(16),
            decoration: BoxDecoration(
              color: colors.card,
              borderRadius: BorderRadius.circular(20),
              border: Border.all(color: colors.border),
            ),
            child: Column(
              children: areasToImprove.map((a) {
                return Padding(
                  padding: const EdgeInsets.only(bottom: 8.0),
                  child: Row(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Icon(FeatherIcons.arrowRight, size: 14, color: colors.coral),
                      const SizedBox(width: 8),
                      Expanded(
                        child: Text(a, style: AppTypography.regular(11, color: colors.foreground, height: 1.4)),
                      ),
                    ],
                  ),
                );
              }).toList(),
            ),
          ),

          // Actionable Study Plan
          if (studyPlan.isNotEmpty) ...[
            const SectionTitle(title: 'Actionable Study Roadmap'),
            ...studyPlan.map((plan) {
              return Container(
                margin: const EdgeInsets.only(bottom: 10),
                padding: const EdgeInsets.all(14),
                decoration: BoxDecoration(
                  color: colors.secondary,
                  borderRadius: BorderRadius.circular(16),
                ),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Row(
                      mainAxisAlignment: MainAxisAlignment.spaceBetween,
                      children: [
                        Text(plan.topic, style: AppTypography.bold(13, color: colors.foreground)),
                        PillBadge(label: plan.estimatedTime, tone: PillTone.muted),
                      ],
                    ),
                    const SizedBox(height: 4),
                    Text(plan.rationale, style: AppTypography.regular(10, color: colors.mutedForeground, height: 1.4)),
                    const SizedBox(height: 8),
                    Container(
                      padding: const EdgeInsets.all(8),
                      decoration: BoxDecoration(
                        color: colors.card,
                        borderRadius: BorderRadius.circular(10),
                      ),
                      child: Row(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          Icon(FeatherIcons.zap, size: 12, color: colors.primary),
                          const SizedBox(width: 6),
                          Expanded(
                            child: Text(
                              'Drill: ${plan.actionDrill}',
                              style: AppTypography.semiBold(10, color: colors.foreground),
                            ),
                          ),
                        ],
                      ),
                    ),
                  ],
                ),
              );
            }),
          ],

          const SizedBox(height: 20),

          // Action Buttons
          Row(
            children: [
              Expanded(
                child: AppButton(
                  label: 'Question Breakdown',
                  icon: FeatherIcons.list,
                  variant: ButtonVariant.secondary,
                  onPress: () {
                    Navigator.of(context).push(
                      MaterialPageRoute(builder: (_) => const QuestionReviewPage()),
                    );
                  },
                ),
              ),
              const SizedBox(width: 10),
              Expanded(
                child: AppButton(
                  label: 'Export Debrief',
                  icon: FeatherIcons.share2,
                  onPress: () => _showShareReportModal(context, eval, config),
                ),
              ),
            ],
          ),
          const SizedBox(height: 10),
          AppButton(
            label: 'Start Another Session',
            icon: FeatherIcons.refreshCw,
            variant: ButtonVariant.secondary,
            onPress: () {
              Navigator.of(context).pushReplacement(
                MaterialPageRoute(builder: (_) => const CreateInterviewPage()),
              );
            },
          ),
          const SizedBox(height: 30),
        ],
      ),
    );
  }
}
